/**
 * Turning a C2PA manifest into something a person can act on.
 *
 * The hard part here is not parsing, it is honesty. Content Credentials prove
 * exactly one thing: that a named signer attached a set of claims to this file
 * and the file has not changed since. They do not prove the claims are true,
 * and their absence proves nothing whatsoever.
 *
 * Every AI detector on the internet overstates what it knows. This file is
 * written so the product cannot do that: each reading carries an explicit
 * confidence, and the "no credentials" case says plainly that it means nothing.
 */

export type Verdict =
  | 'none'
  | 'tampered'
  | 'ai-generated'
  | 'ai-assisted'
  | 'camera'
  | 'edited'
  | 'signed';

export type Confidence = 'proven' | 'claimed' | 'unknown';

export interface Step {
  label: string;
  software: string | null;
  when: string | null;
}

export interface Signer {
  issuer: string | null;
  time: string | null;
  algorithm: string | null;
}

export interface Reading {
  verdict: Verdict;
  headline: string;
  explanation: string;
  confidence: Confidence;
  signer: Signer | null;
  /** The tool or device that claims to have produced the file. */
  producer: string | null;
  sourceLabel: string | null;
  steps: Step[];
  ingredients: string[];
  aiTraining: 'allowed' | 'not-allowed' | 'unstated';
  /** Whether the signing certificate itself is recognised. */
  signerTrust: 'trusted' | 'unrecognised' | 'expired' | 'revoked';
  warnings: string[];
}

/** Loose shape of what the SDK hands back, so this stays testable with plain objects. */
export interface ManifestStoreLike {
  active_manifest?: string | null;
  manifests?: Record<string, Record<string, unknown>>;
  validation_status?: Array<{ code?: string; explanation?: string }>;
  validation_results?: unknown;
}

